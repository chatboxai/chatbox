import {
  isRowsSessionRecord,
  type SessionRecordStorePort,
  type StoredSessionRecord,
} from '../../ports/session-record-store'
import {
  SessionRowConflictError,
  type SessionRowSnapshot,
  type SessionRowStorePort,
  type SessionRows,
  type SessionRowsDiff,
} from '../../ports/session-row-store'
import { decodeSessionTree, normalizeSessionV1, type SessionRecordV2 } from '../../session/session-tree'
import type { Session } from '../../types/session'
import { migrateSession } from './compatibility/session-load'

export interface PersistedSessionVersion {
  /** Stable across V1 and V2 representations of the same logical session. */
  fingerprint: string
  /** Authoritative row revision, or null while the complete V1 record is authoritative. */
  revision: number | null
}

export interface KnownRowState {
  snapshot: SessionRowSnapshot
  session: Session
  version: PersistedSessionVersion
}

export interface PersistedSessionDeletionState {
  record: StoredSessionRecord | null
  revision: number | null
}

/**
 * Every durable combination that can exist across the record and row stores.
 *
 * The `legacy` and `interrupted-promotion` branches are the compatibility
 * boundary. They can be removed only after released-channel migration
 * telemetry shows no remaining V1 records for the supported upgrade horizon,
 * and the oldest supported backup/import format no longer emits V1 sessions.
 */
export type PersistedSessionState =
  | {
      kind: 'missing'
      revision: number | null
    }
  | {
      kind: 'legacy'
      record: Session
      session: Session
      revision: number | null
      version: PersistedSessionVersion
    }
  | {
      kind: 'interrupted-promotion'
      record: Session
      session: Session
      revision: number
      version: PersistedSessionVersion
    }
  | {
      kind: 'rows'
      marker: SessionRecordV2
      session: Session
      version: PersistedSessionVersion
      snapshot: SessionRowSnapshot
    }

export type PromotionResult =
  | { kind: 'committed'; snapshot: SessionRowSnapshot }
  | { kind: 'anchored'; reason: unknown }

function stableSerialize(value: unknown): string {
  return (
    JSON.stringify(value, (_key, item: unknown) => {
      if (!item || typeof item !== 'object' || Array.isArray(item)) return item
      return Object.fromEntries(
        Object.entries(item as Record<string, unknown>).sort(([left], [right]) => left.localeCompare(right))
      )
    }) ?? String(value)
  )
}

function hash32(value: string, seed: number): string {
  let hash = seed >>> 0
  for (let index = 0; index < value.length; index += 1) {
    hash = Math.imul(hash ^ value.charCodeAt(index), 0x01000193) >>> 0
    hash ^= hash >>> 13
  }
  return hash.toString(16).padStart(8, '0')
}

/** Compact representation-independent token used before a V1 or V2 update. */
export function sessionContentFingerprint(session: Session): string {
  const migrated = migrateSession(session)
  const normalized = normalizeSessionV1(migrated)
  const comparable = normalized.ok ? migrateSession(normalized.session) : migrated
  // Fork list IDs are presentation identifiers regenerated by the codec for empty branches.
  // Match the round-trip verifier's content equivalence without discarding message IDs or topology.
  const content =
    normalized.ok && comparable.messageForksHash
      ? {
          ...comparable,
          messageForksHash: Object.fromEntries(
            Object.entries(comparable.messageForksHash).map(([pivotId, fork]) => [
              pivotId,
              { ...fork, lists: fork.lists.map(({ id: _id, ...list }) => list) },
            ])
          ),
        }
      : comparable
  const serialized = stableSerialize(content)
  return `${serialized.length.toString(36)}:${hash32(serialized, 0x811c9dc5)}:${hash32(serialized, 0x9e3779b9)}`
}

function decodeSnapshot(snapshot: SessionRowSnapshot): Session {
  const decoded = decodeSessionTree({
    session: snapshot.record,
    threads: snapshot.rows.threads,
    messages: snapshot.rows.messages,
  })
  if (!decoded.ok) {
    throw new Error(decoded.reason)
  }
  return migrateSession(decoded.session)
}

function nextRevision(previous: number | null): number {
  if (previous === null) return 1
  if (!Number.isSafeInteger(previous) || previous < 1 || previous === Number.MAX_SAFE_INTEGER) {
    throw new Error('session rows have an invalid commit revision')
  }
  return previous + 1
}

function stateRevision(state: PersistedSessionState): number | null {
  switch (state.kind) {
    case 'missing':
      return state.revision
    case 'legacy':
    case 'interrupted-promotion':
      return state.revision
    case 'rows':
      return state.snapshot.revision
  }
}

/** Owns classification and lifecycle changes spanning the record and row stores. */
export class SessionPersistenceProtocol {
  constructor(
    private readonly records: SessionRecordStorePort,
    private readonly rows: SessionRowStorePort
  ) {}

  async inspectPersistedState(id: string, knownRows?: KnownRowState): Promise<PersistedSessionState> {
    const record = await this.records.getRecord(id)
    if (!record || typeof record !== 'object') {
      const revision = await this.rows.getRevision(id)
      return { kind: 'missing', revision }
    }
    if (record && isRowsSessionRecord(record)) {
      const snapshot = await this.readSnapshot(id, knownRows)
      if (!snapshot) {
        throw new Error(`session ${id} is stored as rows but has none`)
      }
      const session = knownRows?.snapshot.revision === snapshot.revision ? knownRows.session : decodeSnapshot(snapshot)
      return {
        kind: 'rows',
        marker: record,
        session,
        snapshot,
        version: {
          fingerprint:
            knownRows?.snapshot.revision === snapshot.revision
              ? knownRows.version.fingerprint
              : sessionContentFingerprint(session),
          revision: snapshot.revision,
        },
      }
    }

    const revision = await this.rows.getRevision(id)
    const session = migrateSession(record)
    const version = { fingerprint: sessionContentFingerprint(session), revision: null }
    // The complete V1 record is authoritative until a row marker is published.
    // Residual row payloads are inspected only when attempting to reuse a promotion.
    if (revision === null || !(await this.rows.hasRows(id))) {
      return { kind: 'legacy', record, session, revision, version }
    }
    return {
      kind: 'interrupted-promotion',
      record,
      session,
      revision,
      version,
    }
  }

  /** Completes record-first deletions that were interrupted before row cleanup. */
  async recoverOrphanedRows(runExclusive: (id: string, action: () => Promise<void>) => Promise<void>): Promise<void> {
    const [recordIds, rowIds] = await Promise.all([this.records.listIds(), this.rows.listSessionIds()])
    const records = new Set(recordIds)
    for (const id of rowIds) {
      if (records.has(id)) continue
      await runExclusive(id, async () => {
        const revision = await this.rows.getRevision(id)
        if (await this.records.getRecord(id)) return
        await this.rows.deleteRows(id, revision)
      })
    }
  }

  async promote(
    state: PersistedSessionState,
    session: Session,
    rows: SessionRows,
    record: SessionRecordV2
  ): Promise<PromotionResult> {
    if (state.kind === 'rows') {
      return { kind: 'committed', snapshot: state.snapshot }
    }
    if (state.kind === 'interrupted-promotion') {
      return this.recover(state, session, rows, record)
    }
    return this.publishPromotion(state, session, rows, record)
  }

  async commit(
    id: string,
    diff: SessionRowsDiff,
    record: SessionRecordV2,
    expectedRevision: number,
    rows: SessionRows
  ): Promise<SessionRowSnapshot> {
    if (diff.sessionId !== id || rows.sessionId !== id || record.id !== id) {
      throw new Error(`session ${id} commit payloads do not share an id`)
    }
    const revision = nextRevision(expectedRevision)
    await this.rows.applyDiff(diff, { record, revision }, expectedRevision)
    return { rows, record, revision }
  }

  /** Deletion needs the recovery record and CAS revision, not readable message content. */
  async inspectDeletionState(id: string): Promise<PersistedSessionDeletionState> {
    const record = await this.records.getRecord(id)
    const revision = await this.rows.getRevision(id)
    return { record, revision }
  }

  async delete(id: string, state: PersistedSessionDeletionState): Promise<void> {
    const { record, revision } = state
    try {
      await this.records.removeRecord(id)
    } catch (error) {
      if (await this.records.getRecord(id)) throw error
    }
    try {
      await this.rows.deleteRows(id, revision)
    } catch (error) {
      if (record) {
        await this.records.setRecord(record)
      }
      throw error
    }
  }

  private async recover(
    state: Extract<PersistedSessionState, { kind: 'interrupted-promotion' }>,
    session: Session,
    rows: SessionRows,
    record: SessionRecordV2
  ): Promise<PromotionResult> {
    const intendedFingerprint = sessionContentFingerprint(session)
    const snapshot = intendedFingerprint === state.version.fingerprint ? await this.readPromotionCandidate(state) : null
    if (snapshot) {
      try {
        await this.records.setRecord(snapshot.record)
        return { kind: 'committed', snapshot }
      } catch (error) {
        const current = await this.records.getRecord(record.id)
        if (current && isRowsSessionRecord(current)) {
          return { kind: 'committed', snapshot }
        }
        return { kind: 'anchored', reason: error }
      }
    }
    return this.publishPromotion(state, session, rows, record)
  }

  private async readPromotionCandidate(
    state: Extract<PersistedSessionState, { kind: 'interrupted-promotion' }>
  ): Promise<SessionRowSnapshot | null> {
    let snapshot: SessionRowSnapshot | null
    let fingerprint: string
    try {
      snapshot = await this.rows.readSnapshot(state.record.id)
      if (!snapshot) return null
      fingerprint = sessionContentFingerprint(decodeSnapshot(snapshot))
    } catch {
      // Invalid remnants can be rebuilt from the complete V1 record by a revision-checked write.
      return null
    }
    if (snapshot.revision !== state.revision) {
      throw new SessionRowConflictError(state.record.id, state.revision, snapshot.revision)
    }
    return fingerprint === state.version.fingerprint ? snapshot : null
  }

  private async publishPromotion(
    state: PersistedSessionState,
    session: Session,
    rows: SessionRows,
    record: SessionRecordV2
  ): Promise<PromotionResult> {
    await this.records.setRecord(session)
    const revision = nextRevision(stateRevision(state))
    const snapshot = { rows, record, revision }
    try {
      await this.rows.writeRows(snapshot, stateRevision(state))
      await this.records.setRecord(record)
      return { kind: 'committed', snapshot }
    } catch (error) {
      if (error instanceof SessionRowConflictError) throw error
      const current = await this.records.getRecord(record.id)
      if (current && isRowsSessionRecord(current)) {
        const committed = await this.rows.readSnapshot(record.id)
        if (committed) return { kind: 'committed', snapshot: committed }
      }
      if (current) return { kind: 'anchored', reason: error }
      throw error
    }
  }

  private async readSnapshot(id: string, knownRows?: KnownRowState): Promise<SessionRowSnapshot | null> {
    const revision = await this.rows.getRevision(id)
    if (knownRows && knownRows.snapshot.revision === revision) {
      return knownRows.snapshot
    }
    return this.rows.readSnapshot(id)
  }
}
