/**
 * sha256.js — 同步 SHA-256（纯 JS，无依赖）
 *
 * 为什么不用 Node 的 crypto：这些模块同时被两侧加载——
 *   - Node 侧：context-amp-mcp 的 MCP server 直接 require
 *   - 渲染进程：Chatbox 的上下文放大器打包进 bundle
 * 渲染进程没有 Node crypto，Rollup 会把它转成一个空的 require$$0，
 * `crypto.createHash` 变成 undefined，戳生成直接抛异常（表现为"哈希值
 * 没有被创建"）。
 *
 * 也不用 Web Crypto（crypto.subtle.digest）：它是异步的，而 generateStamp
 * 被 detectTaskBlocks → classifyBlocks → amplifyContext 同步调用，改成
 * 异步会波及整条链路。
 *
 * 纯 JS 实现保证两侧产出完全一致的戳，且保持同步签名。
 */

