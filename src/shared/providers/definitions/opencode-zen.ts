// OpenCode Zen is the pay-as-you-go tier of the same console as OpenCode Go, with the full
// catalog (GPT / Claude / Gemini / Grok plus open models). API-key auth only
// (https://opencode.ai/auth); there is no official OAuth. Requests go to /zen/v1 and are
// routed by model id across four surfaces: Gemini uses the Google generative API,
// Claude / Qwen use Anthropic Messages, GPT / Grok / Muse Spark use Responses, and
// everything else uses Chat Completions.

export const OPENCODE_ZEN_API_HOST = 'https://opencode.ai/zen/v1'
export const OPENCODE_ZEN_AUTH_URL = 'https://opencode.ai/auth'
export const OPENCODE_ZEN_DOCS_URL = 'https://opencode.ai/docs/zen/'
export const OPENCODE_ZEN_MODELS_URL = 'https://opencode.ai/zen/v1/models'

const ROUTING_RULES: OpenCodeRoutingRules = {
  google: ['gemini-'],
  anthropic: ['claude-', 'qwen3.'],
  responses: ['gpt-', 'grok-', 'muse-spark'],
}

export function getOpenCodeZenApiStyle(modelId: string): OpenCodeApiStyle {
  return resolveOpenCodeApiStyle(modelId, ROUTING_RULES)
}

export function applyOpenCodeZenModelMetadata(model: ProviderModelInfo): ProviderModelInfo {
  return {
    ...model,
    // Always overwrite: getModel() may stamp the provider type (`openai`) before
    // createModel runs, which would otherwise pin Claude/Gemini onto the wrong surface.
    apiStyle: getOpenCodeZenApiStyle(model.modelId),
  }
}

const MODEL_CLASSES = defineOpenCodeModelClasses('OpenCode Zen', (models) => models.map(applyOpenCodeZenModelMetadata))

