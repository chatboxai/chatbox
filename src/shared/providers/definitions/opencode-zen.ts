export const opencodeZenProvider = defineProvider({
  id: ModelProviderEnum.OpenCodeZen,
  name: 'OpenCode Zen',
  type: ModelProviderType.OpenAI,
  urls: {
    website: 'https://opencode.ai',
    apiKey: OPENCODE_ZEN_AUTH_URL,
    docs: OPENCODE_ZEN_DOCS_URL,
    models: OPENCODE_ZEN_MODELS_URL,
  },
  defaultSettings: {
    apiHost: OPENCODE_ZEN_API_HOST,
    models: DEFAULT_MODELS,
  },
  createModel: (config) =>
    createOpenCodeModel(config, {
      classes: MODEL_CLASSES,
      defaultApiHost: OPENCODE_ZEN_API_HOST,
      defaultModels: DEFAULT_MODELS,
      getApiStyle: getOpenCodeZenApiStyle,
    }),
  getDisplayName: (modelId, providerSettings) => {
    return `OpenCode Zen (${providerSettings?.models?.find((m) => m.modelId === modelId)?.nickname || modelId})`
  },
})
